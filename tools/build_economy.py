"""Compile reviewable economy tables into native Emuera functions."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def compile_rules():
    data = json.loads((ROOT / 'content/economy_rules.json').read_text(encoding='utf-8-sig'))
    lines = ['; Generated by tools/build_economy.py; edit content/economy_rules.json.']
    for key, maximum in [('resources', 4), ('facilities', 12), ('projects', 3), ('recipes', 3)]:
        assert [r['id'] for r in data[key]] == list(range(1, maximum + 1))
    for function, key, field in [('EC_RESOURCE_NAME', 'resources', 'name'),
                                  ('EC_FACILITY_NAME', 'facilities', 'name'),
                                  ('EC_FACILITY_PURPOSE', 'facilities', 'purpose'),
                                  ('EC_PROJECT_NAME', 'projects', 'name'),
                                  ('EC_PROJECT_EFFECT', 'projects', 'effect'),
                                  ('EC_RECIPE_NAME', 'recipes', 'name')]:
        lines += ['', '@' + function + '(EC_ID)', '#FUNCTIONS', '#DIM DYNAMIC EC_ID', 'SELECTCASE EC_ID']
        for row in data[key]:
            value = row[field]
            assert isinstance(value, str) and value and not any(c in value for c in '\n\r{}')
            lines += [f'CASE {row["id"]}', '\tRETURNF ' + json.dumps(value, ensure_ascii=False)]
        lines += ['ENDSELECT', 'RETURNF "未知"']
    for function, key, fields in [('EC_RESOURCE_VALUE', 'resources', ['price', 'initial']),
                                  ('EC_PROJECT_VALUE', 'projects', ['gold', 'materials', 'mana', 'work']),
                                  ('EC_UPKEEP', 'facilities', ['upkeep'])]:
        lines += ['', '@' + function + '(EC_ID, EC_FIELD = 0)', '#FUNCTION', '#DIM DYNAMIC EC_ID',
                  '#DIM DYNAMIC EC_FIELD', 'SELECTCASE EC_ID * 10 + EC_FIELD']
        for row in data[key]:
            for i, field in enumerate(fields):
                assert type(row[field]) is int and row[field] >= 0
                lines += [f'CASE {row["id"] * 10 + i}', f'\tRETURNF {row[field]}']
        lines += ['ENDSELECT', 'RETURNF 0']
    lines += ['', '@EC_RECIPE_VALUE(EC_ID, EC_RESOURCE, EC_OUTPUT = 0)', '#FUNCTION',
              '#DIM DYNAMIC EC_ID', '#DIM DYNAMIC EC_RESOURCE', '#DIM DYNAMIC EC_OUTPUT',
              'SELECTCASE EC_ID * 100 + EC_OUTPUT * 10 + EC_RESOURCE']
    for row in data['recipes']:
        for side, field in enumerate(('input', 'output')):
            assert len(row[field]) == 5 and all(type(v) is int and v >= 0 for v in row[field])
            for r in range(1, 5):
                lines += [f'CASE {row["id"] * 100 + side * 10 + r}', f'\tRETURNF {row[field][r]}']
    lines += ['ENDSELECT', 'RETURNF 0', '']
    return '\r\n'.join(lines).encode('utf-8-sig')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = compile_rules()
    target = ROOT / 'ERB/ECONOMY_RULES.ERB'
    if args.check:
        assert target.read_bytes() == result, 'Economy tables need regeneration'
    else:
        target.write_bytes(result)
    print('PASS: native economy resource, facility, project and recipe tables')
